def _volume(text: str) -> int:
    """`10000`, `10k`, `2.5M`."""
    cleaned = text.strip().lower().replace(",", "").replace("_", "")
    factor = {"k": 1_000, "m": 1_000_000}.get(cleaned[-1:], 1)
    number = cleaned[:-1] if factor != 1 else cleaned
    try:
        volume = int(float(number) * factor)
    except ValueError as exc:
        raise ConfigError(f"'{text}' is not a monthly volume (use 10000, 10k or 2.5M)") from exc
    if volume <= 0:
        raise ConfigError(f"'{text}' is not a positive monthly volume")
    return volume


def _curve_configs(args: argparse.Namespace) -> list[ProviderConfig]:
    if args.file:
        return [parse_config(Path(path)) for path in args.file]
    specs = discover(_providers_dir(args))
    if args.providers:
        ids = [part.strip() for part in args.providers.split(",") if part.strip()]
        unknown = sorted(set(ids) - set(specs))
        if unknown:
            raise ConfigError(f"unknown provider(s) {unknown}; available: {sorted(specs)}")
    else:
        ids = list(load_config(Path(args.config).resolve()).providers)
    return [specs[provider_id].config for provider_id in ids]


def cmd_curve(args: argparse.Namespace) -> int:
    """The declared price of 1,000 base-shape searches at several monthly volumes."""
    day = _day(args.date)
    volumes = [_volume(part) for part in args.volumes.split(",")] if args.volumes else None
    headline = volumes or list(LADDER_VOLUMES if args.ladder else HEADLINE_VOLUMES)
    configs = _curve_configs(args)

    document: dict[str, object] = {"date": day.isoformat(), "shape": "base", "providers": {}}
    rows: list[list[str]] = []
    reasons: list[str] = []
    for config in configs:
        billing = billing_at(config, day)
        if isinstance(billing, Unknown):
            rows.append([config.name] + ["unknown"] * len(headline))
            reasons.append(f"{config.name}: {billing.reason}")
            continue
        # The table shows the headline volumes; the JSON carries the whole curve.
        wanted = volumes if volumes is not None else None
        points = price_curve(Shape(), billing, wanted, beyond_plan=not args.plan_only)
        by_volume = {point.monthly_volume: point.quote for point in points}
        row = [config.name]
        for volume in headline:
            quote = by_volume[volume]
            if isinstance(quote, Unknown):
                row.append("not published")
                reasons.append(f"{config.name} at {volume:,}: {quote.reason}")
            else:
                plan = f" ({quote.plan_name})" if quote.plan_name else ""
                row.append(f"${quote.price_per_1k:,.2f}{plan}")
        rows.append(row)
        document["providers"][config.id] = {  # type: ignore[index]
            "name": config.name,
            "currency": billing.currency,
            "effective_from": billing.effective_from.isoformat(),
            "checked_at": billing.checked_at.isoformat(),
            "sources": billing.sources,
            "unit": billing.meter.unit_label or billing.meter.unit,
            "units_per_search": billing.request_cost.base,
            "per_search": per_search(config, billing),
            "failed_request_charged": billing.charges.failed_request.charged,
            "points": [
                {"monthly_volume": point.monthly_volume, "price_per_1k": None,
                 "reason": point.quote.reason}
                if isinstance(point.quote, Unknown)
                else {
                    "monthly_volume": point.monthly_volume,
                    "price_per_1k": round(point.quote.price_per_1k, 6),
                    "monthly_cost": round(point.quote.monthly_cost, 2),
                    "plan": point.quote.plan_name,
                    "plan_price": point.quote.plan_price,
                    "extra_cost": round(point.quote.extra_cost, 2),
                    "extra": point.quote.extra,
                    "formula": point.quote.formula,
                    "notes": list(point.quote.notes),
                }
                for point in points
            ],
        }  # fmt: skip

    if args.json:
        print(json.dumps(document, indent=2))
        return 0
    print(f"Declared price of 1,000 searches by monthly volume, in force on {day}.")
    print("Base shape: the benchmarked mode, desktop, page 1, country-level location.")
    if args.plan_only:
        print("Rule: the cheapest published plan that includes the whole volume. Overage and")
        print("early renewal are NOT counted. This is not the rule the benchmark publishes.")
    else:
        print("Rule: the cheapest published way to cover the volume under the provider's own")
        print("terms (a plan, or a smaller plan plus its overage or early renewal), per 1,000.")
    print()
    print(_table(["Provider"] + [f"{volume:,} / month" for volume in headline], rows))
    if reasons:
        print()
        for reason in reasons:
            print(f"  {reason}")
    print()
    print("`serp-bench price --provider ID --volume N` shows the formula behind one figure.")
    return 0


