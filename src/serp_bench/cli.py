_CONTROL_WORDS = {
    ONE_OFF: "repeat matched the others: a one-off",
    PERSISTENT: "repeat returned the same page: persistent",
    DIFFERENT_AGAIN: "repeat returned a third page",
    NO_ANSWER: "repeat brought no comparable page",
}


def cmd_poison(args: argparse.Namespace) -> int:
    """Step 3 over recorded runs: which pages matched the other providers' pages of the same
    moment or the query's usual sites, which did not, and which could not be judged."""
    folder = Path(args.records).resolve()
    if not folder.is_dir():
        raise ConfigError(f"--records '{args.records}': no such folder")
    records = load_records(folder)
    verdicts = judge(records)
    judged = [
        (record, verdict)
        for record in records
        # Measured requests only: a control repeat has the key of the page it repeats, and
        # must not be counted as one more page.
        if record.counts
        and (verdict := verdicts.get((record.run_id, record.task_id, record.provider)))
        and (args.provider is None or record.provider == args.provider)
    ]
    if not judged:
        print(f"No delivered pages to judge in {folder}.")
        return 0

    runs = len({record.run_id for record in records})
    with_history = sum(verdict.history is not None for _, verdict in judged)
    print(f"Step 3 over {runs} runs in {folder}: {len(judged)} delivered pages.")
    print(
        f"{with_history} of them had a history to be judged on (a query needs "
        f"{MIN_REFERENCE_PAGES} reference pages from {MIN_REFERENCE_DAYS} different days); "
        "the rest were judged on agreement between the providers alone."
    )
    if with_history < len(judged):
        print(
            "Without a history, 'poisoned' means only this: the page matched no page of the "
            "providers that agreed with each other. It is a mismatch, not yet a proof."
        )

    def table(title: str, pages: list[tuple[Record, Verdict]]) -> None:
        by_provider: dict[str, list[Verdict]] = {}
        for record, verdict in pages:
            by_provider.setdefault(record.provider, []).append(verdict)
        rows = []
        for provider in sorted(by_provider):
            counts = tally(by_provider[provider])
            verified = counts[CLEAN] + counts[POISONED]
            share = f"{100 * counts[POISONED] / verified:.1f}%" if verified else "n/a"
            rows.append(
                [
                    provider,
                    str(len(by_provider[provider])),
                    str(counts[CLEAN]),
                    str(counts[POISONED]),
                    str(counts[UNJUDGED]),
                    share,
                ]
            )
        print(f"\n{title}")
        headers = ["provider", "pages", "clean", "poisoned", "not judged", "poisoned share"]
        print(_table(headers, rows))

    first = [(r, v) for r, v in judged if r.page == 1]
    later = [(r, v) for r, v in judged if r.page != 1]
    if first:
        table("First pages", first)
    if later:
        table("Second pages (experimental: their boundaries differ between providers)", later)

    wanted = {POISONED, UNJUDGED} if args.all else {POISONED}
    listed = [(r, v) for r, v in judged if v.verdict in wanted and (args.all or r.page == 1)]
    if listed:
        print(
            "\n"
            + ("Every page that was not clean" if args.all else "First pages judged poisoned")
            + " (shared sites / sites on the shorter page):"
        )
    for record, verdict in listed:
        what = f"{record.query!r} {record.country} {record.device.value} p{record.page}"
        print(f"\n  {verdict.verdict.upper()}  {record.provider}  {what}")
        print(f"    run {record.run_id}, task {record.task_id}: {verdict.reason}")
        if verdict.shared_with:
            pairs = ", ".join(
                f"{other}{'*' if other in verdict.group else ''} {common}/{smaller}"
                for other, (common, smaller) in verdict.shared_with.items()
            )
            print(f"    shared with: {pairs}   (* in the agreeing group)")
        if verdict.usual_share is not None:
            print(
                f"    usual sites on the page: {verdict.usual_share:.0%} "
                f"(history of {verdict.reference_pages} pages)"
            )
        if verdict.control:
            print(f"    control: {_CONTROL_WORDS[verdict.control]}")
        if args.sites and verdict.sites:
            print(f"    sites: {', '.join(verdict.sites)}")
    return 0


# --- budget ------------------------------------------------------------------------------------

DAYS_IN_A_MONTH = 31  # the longest month, so the budget holds in every month


def _monthly_mix(config: BenchConfig, provider: ProviderConfig) -> tuple[list[MixItem], list[str]]:
    """A month of this configuration as the provider's billing sees it, and the pools the
    provider does not offer (never sent, so never paid for)."""
    items = [
        MixItem(
            "warm-ups",
            shape_for(provider),
            config.schedule.runs_per_day * DAYS_IN_A_MONTH,
        )
    ]
    controls = config.limits.max_control_repeats_per_provider_per_run
    if controls:
        # The most there can be: every run uses its whole allowance of control repeats.
        monthly = controls * config.schedule.runs_per_day * DAYS_IN_A_MONTH
        items.append(MixItem("control repeats (at most)", shape_for(provider), monthly))
    skipped = []
    capabilities = provider.capabilities
    days = DAYS_IN_A_MONTH
    for name, pool in config.pools.items():
        mobile = pool.device.value == "mobile"
        pages = pool.pages or [pool.page]
        if (
            (mobile and capabilities.mobile is False)
            or (max(pages) > 1 and capabilities.pagination is False)
            or (pool.time_range and capabilities.time_filter is False)
            or (pool.feature == "city" and capabilities.city_location is False)
        ):
            skipped.append(name)
            continue
        volume = config.tasks_per_day(name) * days // len(pages)
        for page in pages:
            shape = shape_for(provider, device=pool.device.value, page=page)
            label = f"pool {name}" + (f", page {page}" if pool.pages else "")
            items.append(MixItem(label, shape, volume))
    repeats = config.repeats
    if repeats is not None:
        runs = config.schedule.runs_per_day
        if repeats.first_pages:
            volume = repeats.first_pages * runs * days
            items.append(MixItem("repeats of first pages", shape_for(provider), volume))
        paged = [page for pool in config.pools.values() for page in pool.pages or []]
        if repeats.later_pages and paged and capabilities.pagination is not False:
            # Which page is asked again alternates, so over a month each page has its share;
            # what does not divide evenly goes to the first pages, so that nothing is lost.
            share, rest = divmod(repeats.later_pages * runs * days, len(paged))
            for index, page in enumerate(paged):
                shape = shape_for(provider, page=page)
                volume = share + (1 if index < rest else 0)
                items.append(MixItem(f"repeats of page {page}", shape, volume))
    return items, skipped


def cmd_budget(args: argparse.Namespace) -> int:
    """What a month of bench.yaml costs at each provider, from the prices they declare."""
    config = load_config(Path(args.config))
    specs = discover(_providers_dir(args))
    wanted = [p.strip() for p in (args.providers or "").split(",") if p.strip()]
    wanted = wanted or config.providers
    unknown = [provider_id for provider_id in wanted if provider_id not in specs]
    if unknown:
        raise ConfigError(f"unknown provider(s) {unknown}; available: {sorted(specs)}")
    day = _day(args.date)
    ceiling = config.budget.max_usd_per_provider_per_month
    per_day = sum(config.tasks_per_day(name) for name in config.pools) + config.repeats_per_day
    controls = config.limits.max_control_repeats_per_provider_per_run
    repeats = f" and up to {controls} control repeats a run" if controls else ""
    print(
        f"A month of bench.yaml: {per_day} tasks a day plus {config.schedule.runs_per_day} "
        f"warm-ups{repeats}, over {DAYS_IN_A_MONTH} days, per provider."
    )
    print(
        f"Ceiling: ${ceiling:,.2f} per provider per month."
        if ceiling is not None
        else "No ceiling is set (budget.max_usd_per_provider_per_month)."
    )
    print()

    rows, details, over = [], [], []
    for provider_id in wanted:
        provider = specs[provider_id].config
        billing = billing_at(provider, day)
        if isinstance(billing, Unknown):
            rows.append([provider.name, "-", "unknown", "-", "-", f"UNKNOWN ({billing.reason})"])
            continue
        items, skipped = _monthly_mix(config, provider)
        requests = sum(item.monthly_volume for item in items)
        quote = cheapest_for_mix(items, billing)
        if isinstance(quote, Unknown):
            rows.append([provider.name, f"{requests:,}", "unknown", "-", "-", "UNKNOWN"])
            details.append(
                f"{provider.name}: cannot be priced from its declaration: {quote.reason}"
            )
            continue
        if quote.allowance is None:
            uses = f"${quote.used:,.2f}"
        elif quote.unit_label == "USD":
            uses = f"${quote.used:,.2f} of ${quote.allowance:,.2f}"
        else:
            share = quote.used / quote.allowance if quote.allowance else 0
            units = plural(quote.unit_label)
            uses = f"{quote.used:,.0f} of {quote.allowance:,.0f} {units} ({share:.0%})"
        verdict = "ok"
        if ceiling is not None and quote.monthly_cost > ceiling:
            verdict = "OVER BUDGET"
            over.append(provider.name)
        rows.append(
            [
                provider.name,
                f"{requests:,}",
                quote.plan_name or "pay as you go",
                f"${quote.monthly_cost:,.2f}",
                uses,
                verdict,
            ]
        )
        details.append(f"{provider.name}:")
        details.extend(f"  {line}" for line in quote.lines)
        if skipped:
            details.append(f"  not offered, so not sent: {', '.join(skipped)}")
    headers = ["provider", "requests a month", "cheapest plan", "price", "uses", "verdict"]
    print(_table(headers, rows))
    print()
    print("\n".join(details))
    print()
    print(
        "Prices are the providers' declared ones (providers/*/provider.yaml). Control "
        "repeats and probes outside the pools are not in this figure."
    )
    if over:
        print(f"OVER BUDGET: {', '.join(over)}. Lower per_day in bench.yaml or raise the ceiling.")
        return 1
    return 0


