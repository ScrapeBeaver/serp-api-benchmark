def _load_dotenv(path: Path) -> None:
    """Read KEY=VALUE lines from a .env file. Real environment variables win."""
    if not path.is_file():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip().strip("'\"")
        if key.strip() and value:
            os.environ.setdefault(key.strip(), value)


def _root(args: argparse.Namespace) -> Path:
    return Path(args.config).resolve().parent


def _providers_dir(args: argparse.Namespace) -> Path:
    if args.providers_dir:
        return Path(args.providers_dir).resolve()
    return _root(args) / "providers"


def _setup(args: argparse.Namespace) -> tuple[BenchConfig, Path, dict[str, ProviderSpec]]:
    config = load_config(Path(args.config).resolve())
    _load_dotenv(_root(args) / ".env")
    return config, _root(args), discover(_providers_dir(args))


def _table(headers: list[str], rows: list[list[str]]) -> str:
    widths = [max(len(cell) for cell in column) for column in zip(headers, *rows, strict=True)]
    lines = ["  ".join(h.ljust(w) for h, w in zip(headers, widths, strict=True)).rstrip()]
    lines.append("  ".join("-" * w for w in widths))
    lines += ["  ".join(c.ljust(w) for c, w in zip(r, widths, strict=True)).rstrip() for r in rows]
    return "\n".join(lines)


def _tri(value: object) -> str:
    return {True: "yes", False: "no"}.get(value, str(value))  # type: ignore[arg-type]


def _day(value: str | None) -> dt.date:
    if value is None:
        return dt.datetime.now(dt.UTC).date()
    try:
        return dt.date.fromisoformat(value)
    except ValueError as exc:
        raise ConfigError(f"--date '{value}' is not YYYY-MM-DD") from exc


def _plan_of(config: ProviderConfig) -> str:
    account = config.current_billing.benchmark_account
    return account.plan if account else "n/a"


def _job_summary(text: str) -> None:
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(text.rstrip() + "\n\n")


