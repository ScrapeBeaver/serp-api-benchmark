def readme_block() -> str:
    return f"{README_START}\n{to_markdown()}\n{README_END}"


def cmd_metrics(args: argparse.Namespace) -> int:
    if not args.update_readme:
        print(to_markdown())
        return 0
    path = Path(args.update_readme)
    text = path.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        raise ConfigError(f"{path}: the metrics markers are missing")
    head, rest = text.split(README_START, 1)
    tail = rest.split(README_END, 1)[1]
    path.write_text(head + readme_block() + tail, encoding="utf-8")
    print(f"{path}: metrics section updated")
    return 0


def cmd_schema(args: argparse.Namespace) -> int:
    print(json.dumps(ProviderConfig.model_json_schema(by_alias=True), indent=2))
    return 0


def _priced_config(args: argparse.Namespace) -> ProviderConfig:
    """The contract to price: a provider folder by id, or any provider.yaml by path."""
    if getattr(args, "file", None):
        return parse_config(Path(args.file))
    if not args.provider:
        raise ConfigError("give --provider ID or --file PATH")
    specs = discover(_providers_dir(args))
    if args.provider not in specs:
        raise ConfigError(f"unknown provider '{args.provider}'; available: {sorted(specs)}")
    return specs[args.provider].config


def cmd_price(args: argparse.Namespace) -> int:
    config = _priced_config(args)
    day = _day(args.date)
    billing = billing_at(config, day)
    if isinstance(billing, Unknown):
        print(f"{config.name}: unknown ({billing.reason})")
        return 0

    shape = shape_for(
        config,
        mode=args.mode,
        device=args.device,
        page=args.page,
        location=args.location,
        query_operators=args.operators,
        ai_overview=args.ai_overview,
    )
    mode = shape.mode or f"{config.product.mode} (benchmarked)"
    extras = [
        name
        for name, on in (("operators", shape.query_operators), ("AI Overview", shape.ai_overview))
        if on
    ]
    print(f"{config.name}: {config.product.name}")
    print(f"Billing in force on {day} (from {billing.effective_from}, read {billing.checked_at})")
    print(
        f"Shape: mode {mode}, {shape.device}, page {shape.page}, {shape.location}-level location"
        + (f", {', '.join(extras)}" if extras else "")
    )

    unit = billing.meter.unit_label or billing.meter.unit
    cost = unit_cost(shape, billing)
    if isinstance(cost, Unknown):
        print(f"Cost of one request: unknown ({cost.reason})")
    else:
        rules = f", {len(cost.rules)} rule(s) applied" if cost.rules else ""
        print(f"Cost of one request: {cost.units:g} {unit}{rules}")

    quote = price_per_1k(shape, args.volume, billing, beyond_plan=not args.plan_only)
    if isinstance(quote, Unknown):
        print(f"Price per 1,000 at {args.volume:,} a month: unknown ({quote.reason})")
    else:
        print(f"Price per 1,000 at {args.volume:,} a month: ${quote.price_per_1k:,.2f}")
        print(f"  {quote.formula}")
        for note in quote.notes:
            print(f"  note: {note}")
    print("Sources: " + ", ".join(billing.sources))
    print("Declared by the provider; what a run was actually charged is in the records.")
    return 0


