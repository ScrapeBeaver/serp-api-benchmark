def cmd_conformance(args: argparse.Namespace) -> int:
    log.setup(args.log_level, args.log_format)
    _load_dotenv(_root(args) / ".env")
    specs = discover(_providers_dir(args))
    if args.provider not in specs:
        raise ConfigError(f"unknown provider '{args.provider}'; available: {sorted(specs)}")
    spec = specs[args.provider]
    provider = spec.create()
    if provider.missing_env:
        raise ConfigError(f"{args.provider}: {', '.join(provider.missing_env)} is not set")
    log.info(
        "conformance_start",
        f"conformance of {provider.id}: {len(conformance.PROBES)} probes, one request each, "
        f"time limit {args.timeout:g} s",
        provider=provider.id,
    )
    report = asyncio.run(conformance.run_conformance(provider, timeout=args.timeout))
    for item in report.probes:
        log.info(
            "conformance_probe",
            f"{item.probe.id}: response {item.response_verdict}, billing {item.billing_verdict}",
            probe=item.probe.id,
            response=item.response_verdict,
            billing=item.billing_verdict,
        )
    path = conformance.write(report, Path(args.out).resolve() if args.out else spec.folder)
    print(conformance.render(report))
    print()
    print(f"Written: {path}")
    _job_summary(f"## Conformance: `{provider.id}`\n\n{conformance.render(report, markdown=True)}")
    return 1 if report.overall == conformance.FAIL else 0


PRICES_MAX_AGE_DAYS = 45  # declared prices older than this are due for a re-read


def _check_examples(providers_dir: Path) -> list[str]:
    """Every contract under providers/_examples must validate and be priceable."""
    problems = []
    for path in sorted((providers_dir / "_examples").glob("*.yaml")):
        try:
            config = parse_config(path)
        except ProviderConfigError as exc:
            problems.append(str(exc))
            continue
        if config.id != path.stem:
            problems.append(f"{path}: id is '{config.id}' but the file is '{path.name}'")
        if config.status != "draft":
            problems.append(f"{path}: an example stays `status: draft`")
        price_curve(Shape(), config.current_billing)  # must not raise
    return problems


def cmd_check_providers(args: argparse.Namespace) -> int:
    """Everything that can be checked about provider folders without a key."""
    providers_dir = _providers_dir(args)
    today = dt.datetime.now(dt.UTC).date()
    on_ci = bool(os.environ.get("GITHUB_ACTIONS"))
    errors = 0
    folders = sorted(
        p for p in providers_dir.iterdir() if p.is_dir() and not p.name.startswith(("_", "."))
    )
    for folder in folders:
        problems: list[str] = []
        warnings: list[str] = []
        spec = None
        try:
            spec = load_spec(folder)
        except ProviderConfigError as exc:
            problems.append(str(exc))
        if spec is not None:
            provider = spec.create(dummy_env(spec))
            paths = fixtures_of(spec)
            if spec.config.auth.env and not paths:
                problems.append("no fixtures: add at least one recorded response in fixtures/")
            for fixture_path in paths:
                try:
                    found = check_fixture(provider, load_fixture(fixture_path))
                except (ValueError, KeyError, TypeError) as exc:
                    found = [f"cannot be read: {exc}"]
                problems += [f"fixtures/{fixture_path.name}: {text}" for text in found]
            for index, entry in enumerate(spec.config.billing):
                if entry.review is not None or not spec.config.auth.env:
                    continue
                text = f"the billing entry from {entry.effective_from} has no `review`"
                if index > 0:
                    problems.append(f"{text}: a price change must be confirmed by a person")
                elif spec.config.status in ("shadow", "published"):
                    warnings.append(f"{text}: its prices were not confirmed by a person")
            read = (today - spec.config.current_billing.checked_at).days
            if spec.config.auth.env and read > PRICES_MAX_AGE_DAYS:
                warnings.append(
                    f"prices were read {read} days ago (limit {PRICES_MAX_AGE_DAYS}): "
                    "re-read the sources and append a billing entry if anything changed"
                )
            if spec.config.status in ("shadow", "published") and spec.config.auth.env:
                age = conformance.age_in_days(folder, today)
                if age is None:
                    warnings.append("no conformance.json: run `serp-bench conformance`")
                elif age > conformance.MAX_AGE_DAYS:
                    warnings.append(
                        f"conformance.json is {age} days old (limit {conformance.MAX_AGE_DAYS})"
                    )
        status = spec.config.status if spec else "?"
        verdict = "FAIL" if problems else "ok"
        print(f"{folder.name:<16} {status:<12} {verdict}")
        for text in problems:
            errors += 1
            print(f"  error: {text}")
            if on_ci:
                print(f"::error title=provider {folder.name}::{text.splitlines()[0]}")
        for text in warnings:
            print(f"  warning: {text}")
            if on_ci:
                print(f"::warning title=provider {folder.name}::{text}")
    example_problems = _check_examples(providers_dir)
    examples = len(list((providers_dir / "_examples").glob("*.yaml")))
    if examples:
        print(f"{'_examples':<16} {examples:<12} {'FAIL' if example_problems else 'ok'}")
    for text in example_problems:
        errors += 1
        print(f"  error: {text}")
        if on_ci:
            print(f"::error title=example contract::{text.splitlines()[0]}")
    print()
    print(f"{len(folders)} provider folder(s) checked, {errors} error(s).")
    return 1 if errors else 0


