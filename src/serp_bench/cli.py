def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="serp-bench", description="A reproducible comparison of Google SERP APIs."
    )
    parser.add_argument("--version", action="version", version=f"serp-bench {__version__}")
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--config", default="bench.yaml", help="path to bench.yaml")
    common.add_argument("--providers-dir", default=None, help="default: providers/ next to it")
    logging_args = argparse.ArgumentParser(add_help=False)
    logging_args.add_argument(
        "--log-level", default="INFO", choices=["DEBUG", "INFO", "WARNING", "ERROR"]
    )
    logging_args.add_argument("--log-format", default="text", choices=["text", "json"])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("providers", parents=[common], help="list the providers found")
    p.set_defaults(func=cmd_providers)

    p = sub.add_parser("plan", parents=[common], help="print the tasks a run would send")
    p.add_argument("--date", help="YYYY-MM-DD, default: today (UTC)")
    p.add_argument("--run", default="auto", help="run index, or auto (the run due this hour)")
    p.add_argument("--seed", type=int, default=0, help="extra salt for the planner")
    p.add_argument("--limit", type=int, help="list only the first N tasks")
    p.set_defaults(func=cmd_plan)

    p = sub.add_parser("run", parents=[common, logging_args], help="run once and write records")
    p.add_argument("--providers", help="comma-separated ids, default: bench.yaml")
    p.add_argument("--date", help="YYYY-MM-DD, default: today (UTC)")
    p.add_argument(
        "--run",
        default="auto",
        help="auto (the run that fell due recently and is not stored yet: what the schedule "
        "asks for), next (the first of today's runs not stored yet), or a run index",
    )
    p.add_argument(
        "--stored",
        metavar="DIR",
        help="folder with the runs stored so far (YYYY/MM/DD/run-*.jsonl.gz), which `auto` "
        "and `next` never repeat; default: raw/ under --out",
    )
