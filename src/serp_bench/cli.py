def _select(
    config: BenchConfig, specs: dict[str, ProviderSpec], requested: str | None, allow_draft: bool
) -> list[Provider]:
    ids = [p.strip() for p in requested.split(",") if p.strip()] if requested else config.providers
    unknown = [provider_id for provider_id in ids if provider_id not in specs]
    if unknown:
        raise ConfigError(f"unknown provider(s) {unknown}; available: {sorted(specs)}")
    drafts = [i for i in ids if specs[i].config.status == "draft"]
    if drafts and not allow_draft:
        raise ConfigError(
            f"{drafts} have status `draft` and are not run. Run `serp-bench conformance "
            "--provider <id>` and move the provider on, or pass --allow-draft."
        )
    providers = []
    for provider_id in dict.fromkeys(ids):
        provider = specs[provider_id].create()
        if provider.missing_env:
            names = ", ".join(provider.missing_env)
            log.warning("provider_skipped", f"skipping {provider_id}: {names} is not set")
            continue
        providers.append(provider)
    return providers


def _records_path(out: Path, day: dt.date, due: str, run_id: str) -> Path:
    folder = out / "raw" / f"{day:%Y}" / f"{day:%m}" / f"{day:%d}"
    path = folder / f"run-{due.replace(':', '')}.jsonl.gz"
    if path.exists():  # never overwrite a run that was already recorded
        path = folder / f"run-{due.replace(':', '')}-{run_id.rsplit('-', 1)[-1]}.jsonl.gz"
    return path


def _log_record(record: Record) -> None:
    """One line per (task, provider): what was asked, what happened, why, and how long."""
    what = f"{record.pool} {record.query_id} {record.country} {record.device.value} p{record.page}"
    if record.warmup:
        what = "warm-up"
    elif record.control:
        what = f"control repeat of {what}"
    timing = ""
    if record.total_ms is not None:
        ttfb = f", first byte {record.ttfb_ms / 1000:.2f} s" if record.ttfb_ms is not None else ""
        timing = f" in {record.total_ms / 1000:.2f} s{ttfb}"
    lag = ""
    if record.dispatch_lag_ms is not None:
        lag = f", sent {record.dispatch_lag_ms:.0f} ms after schedule"
        if record.client_lag:
            lag += " (LATE: our stand)"
    last = record.checks[-1] if record.checks else None
    if record.outcome == OUTCOME_DELIVERED:
        reason = f"{record.organic_count} results"
    elif record.outcome == OUTCOME_VOID:
        reason = f"{record.void_reason}: {last.detail if last else ''}"
    else:
        reason = f"{last.check}: {last.detail}" if last else ""
    log.info(
        "request",
        f"{what} | {record.provider} | {record.outcome}{timing}{lag} | {reason}",
        task_id=record.task_id,
        pool=record.pool,
        provider=record.provider,
        outcome=record.outcome,
        void_reason=record.void_reason,
        failed_check=last.check if last and not last.passed else None,
        detail=last.detail if last else None,
        http_status=record.http_status,
        ttfb_ms=record.ttfb_ms,
        total_ms=record.total_ms,
        dispatch_lag_ms=record.dispatch_lag_ms,
        client_lag=record.client_lag,
        organic_count=record.organic_count,
        billed_units=record.billed_units,
        warmup=record.warmup,
        control=record.control,
    )


def cmd_run(args: argparse.Namespace) -> int:
    log.setup(args.log_level, args.log_format)
    config, root, specs = _setup(args)
    day = _day(args.date)
    now = dt.datetime.now(dt.UTC)
    stored = Path(args.stored) if args.stored else Path(args.out) / "raw"
    if args.run == "auto" and args.date is None:
        # What the schedule asks for. The job may start well after the run fell due, in
        # another hour or on the next day, so the run is found by what is owed, not by
        # the hour on the clock.
        owed = late_run(config, now, stored)
        if owed is None:
            grace = config.schedule.grace.total_seconds() / 3600
            print(
                f"Nothing due at {now:%H:%M} UTC: no run fell due in the last {grace:g} h "
                "that is not stored already."
            )
            return 0
        day, run_index = owed
        config = config.on(day)
        late = (now - config.schedule.due_at(day, run_index)).total_seconds() / 60
        log.info("schedule", f"run {run_index} of {day}, due {late:.0f} min ago")
    else:
        config = config.on(day)  # a day's runs are those of the configuration of that day
        run_index = resolve_run(config, args.run, now, day=day, stored=stored)
    if run_index is None:
        times = ", ".join(
            config.schedule.due_time(day, k) for k in range(config.schedule.runs_per_day)
        )
        if args.run == "next":
            print(f"Nothing to do: every run of {day} is stored already ({times} UTC).")
        elif config.schedule.run_due_in_hour(now) is not None:
            print(f"Nothing to do: the run due in this hour ({now:%H}:00 UTC) is stored already.")
        else:
            print(f"Nothing due: no run is scheduled in the current hour ({now:%H}:00 UTC).")
            print(f"Today's runs are due at {times} UTC. Pass --run next to do the next one now.")
        return 0

    providers = _select(config, specs, args.providers, args.allow_draft)
    if not providers:
        print("error: no provider can run (see the messages above)", file=sys.stderr)
        return 2
    # The order in which each task reaches the providers, drawn for this run.
    order = provider_order(config, day, run_index, [p.id for p in providers], seed=args.seed)
    providers = sorted(providers, key=lambda provider: order.index(provider.id))

    limits = config.limits
    interval = limits.dispatch_interval_seconds if args.interval is None else args.interval
    if interval < 0:
        raise ConfigError("--interval must be 0 or more seconds")
    tasks = plan(config, root, day, run_index, seed=args.seed)
    if args.limit is not None:
        tasks = tasks[: args.limit]
    budget = limits.max_tasks_per_provider_per_run
    controls = limits.max_control_repeats_per_provider_per_run
    if args.controls is not None:
        if args.controls < 0:
            raise ConfigError("--controls must be 0 or more")
        controls = args.controls
    if len(tasks) + 1 > budget:
        log.warning(
            "budget",
            f"{len(tasks)} tasks planned; the run limit is {budget} requests per provider "
            f"including the warm-up, so the first {budget - 1} are sent",
        )
        tasks = tasks[: budget - 1]
    if not tasks:
        print(f"Run {run_index} has no tasks.")
        return 0

    due = config.schedule.due_time(day, run_index)
    run_id = f"{day:%Y%m%d}-r{run_index}-{due.replace(':', '')}-{uuid.uuid4().hex[:6]}"
    path = _records_path(Path(args.out).resolve(), day, due, run_id)
    ctx = RunContext(run_id, config_hash(config, root), config.methodology_version, run_index)

    pools = sorted({task.pool for task in tasks})
    log.info(
        "run_start",
        f"run {run_id}: methodology {config.methodology_version}, configuration "
        f"{ctx.config_hash}, seed {args.seed}; run {run_index} of {day}, due {due} UTC",
        run_id=run_id,
        methodology_version=config.methodology_version,
        config_hash=ctx.config_hash,
        seed=args.seed,
        date=day.isoformat(),
        run_index=run_index,
        due_utc=due,
    )
    for provider in providers:
        pc = provider.config
        log.info(
            "run_provider",
            f"provider {pc.id}: status {pc.status}, plan {_plan_of(pc)}, "
            f"adapter {pc.adapter.version}, {pc.product.name}",
            provider=pc.id,
            status=pc.status,
            plan=_plan_of(pc),
            adapter_version=pc.adapter.version,
            product=pc.product.name,
        )
    stagger = limits.stagger_providers
    ticks = 1 + max((task.tick if task.tick is not None else n) for n, task in enumerate(tasks))
    how = (
        f"to one provider after another, {interval:g} s apart, in the order {', '.join(order)}"
        if stagger
        else "to all providers at once"
    )
    log.info(
        "run_protocol",
        f"{len(tasks)} tasks from pools {', '.join(pools)}; one task every {interval:g} s {how}; "
        f"time limit {limits.timeout_seconds:g} s; at most "
        f"{limits.max_in_flight_per_provider} of our requests in flight per provider; "
        "no retries",
        tasks=len(tasks),
        pools=pools,
        interval_seconds=interval,
        timeout_seconds=limits.timeout_seconds,
        max_in_flight=limits.max_in_flight_per_provider,
        provider_order=order if stagger else None,
        about_seconds=round((ticks + (len(order) - 1 if stagger else 0)) * interval),
    )

    with RecordWriter(path) as writer:
        try:
            records = asyncio.run(
                run_tasks(
                    tasks=tasks,
                    providers=providers,
                    writer=writer,
                    ctx=ctx,
                    timeout=limits.timeout_seconds,
                    interval=interval,
                    max_in_flight=limits.max_in_flight_per_provider,
                    max_requests_per_provider=budget,
                    save_bodies=Path(args.save_bodies).resolve() if args.save_bodies else None,
                    on_record=_log_record,
                    max_control_repeats=controls,
                    stagger=stagger,
                )
            )
        except KeyboardInterrupt:
            print(f"\nRun aborted. {writer.count} records kept in {path}", file=sys.stderr)
            return 130

    log.info("run_end", f"run {run_id} finished: {len(records)} records in {path}",
             run_id=run_id, records=len(records), path=str(path))  # fmt: skip
    if args.log_format == "json":
        log.info("report", "report", report=report_data(records))
    print(render(records))
    print()
    print(f"Records: {path} ({len(records)} lines)")
    print(f"Recompute this report with: serp-bench verify {path}")
    _job_summary(f"## SERP benchmark run `{run_id}`\n\n{render(records, markdown=True)}")
    return 0


