def cmd_explain(args: argparse.Namespace) -> int:
    records = [
        record
        for record in read_records(Path(args.file))
        if record.task_id == args.task and (not args.provider or record.provider == args.provider)
    ]
    if not records:
        raise RecordError(f"{args.file}: no record for task '{args.task}'")
    for record in records:
        print(f"Task {record.task_id}, provider {record.provider} ({record.provider_status})")
        print(
            f'  asked: "{record.query}", country {record.country}, locale {record.locale}, '
            f"{record.device.value}, page {record.page}"
            + (f", place {record.location}" if record.location else "")
        )
        print(f"  pool {record.pool} ({'headline' if record.headline else 'not in the headline'})")
        print(f"  scheduled {record.scheduled_at}, sent {record.started_at}")
        if record.total_ms is not None:
            first = f"{record.ttfb_ms / 1000:.2f} s" if record.ttfb_ms is not None else "n/a"
            print(
                f"  HTTP {record.http_status}, first byte {first}, complete in "
                f"{record.total_ms / 1000:.2f} s, {record.bytes} bytes"
            )
        print("  checks, in order:")
        for item in record.checks:
            mark = "PASS" if item.passed else "FAIL"
            print(f"    {mark}  {item.check:<20} {item.detail}")
            if not item.passed:
                print(f"          rule: {check_definition(item.check).definition}")
        if record.outcome == OUTCOME_DELIVERED:
            meaning = "every check passed"
        elif record.outcome == OUTCOME_VOID:
            meaning = f"{record.void_reason}; excluded from every figure"
        else:
            meaning = "the first check that failed names the outcome"
        print(f"  outcome: {record.outcome} ({meaning})")
        if record.billed_units is not None:
            print(f"  the response says {record.billed_units:g} unit(s) were charged")
        print()
    return 0


